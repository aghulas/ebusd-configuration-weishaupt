"""Generate weishaupt/wtc.history.inc: WTC fault history and 16-bit fault counters (read only).

Format observed on the bus from WCM-Diagnose 5.5.19 (29/10/2026, captured with ebusd grab):
  request  QQ -> ZZ 5000  [CRC] 06 <page> <(len-1)<<4 | 2> <address low>   (several groups may be chained)
  response [00] <len data bytes>
  CRC = Weishaupt CRC8 (polynomial 0x5C, seeded with the first byte), see calculate_weishaupt_crc.py.

Fault history: EEPROM 0x0200-0x0231 = pointer (2 bytes, address of the last byte written) + 6 slots of 8 bytes
from 0x0202: error code (bit 7: 0 = F, 1 = W; bits 0-6: number), I10 operating phase, I11 load setting %,
I22 pump PWM %, I30 boiler temperature, I31 flue gas temperature, I32 ionisation (/10 uA), I37 return temperature.
The most recent entry is the slot ending at the pointer.

Fault counters: EEPROM 0x0196-0x01D7, one unsigned 16-bit counter per fault code (labels from the WCM-Diagnose
"Statistic" tab).

Usage: python3 generate_fault_history.py  (writes ../weishaupt/wtc.history.inc)
"""

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "weishaupt" / "wtc.history.inc"

